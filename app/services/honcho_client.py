"""Honcho v3 REST client — local instance.

Thin async wrapper around the verified /v3 API surface.
One peer per user (pinned at the app layer), sessions under the peer.
Uses shared httpx.AsyncClient for connection pooling.
"""

import uuid

import httpx

from app.core.config import settings

# Shared client for connection pooling. Pinned to its running loop: a pooled
# connection bound to a closed loop (tests, restarts) is worse than useless,
# so a loop change transparently rebuilds the client.
_honcho_client: httpx.AsyncClient | None = None
_honcho_loop = None


def _get_client() -> httpx.AsyncClient:
    import asyncio

    global _honcho_client, _honcho_loop
    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        loop = None
    if _honcho_client is None or _honcho_client.is_closed or _honcho_loop is not loop:
        _honcho_client = httpx.AsyncClient(
            timeout=httpx.Timeout(connect=5, read=15, write=5, pool=3),
            limits=httpx.Limits(max_connections=5, max_keepalive_connections=3),
        )
        _honcho_loop = loop
    return _honcho_client


class HonchoClient:
    def __init__(self, base_url: str | None = None, workspace: str | None = None):
        self.base_url = (base_url or settings.honcho_base_url).rstrip("/")
        self.workspace = workspace or settings.honcho_workspace

    def _url(self, path: str) -> str:
        return f"{self.base_url}/v3/workspaces/{self.workspace}{path}"

    async def ensure_peer(self, peer_id: str) -> dict:
        """Create a peer if missing (idempotent)."""
        from app.services.processing_boundary import permit_external_processing
        await permit_external_processing()
        client = _get_client()
        resp = await client.post(self._url("/peers"), json={"name": peer_id})
        resp.raise_for_status()
        return resp.json()

    async def get_peer_context(self, peer_id: str) -> dict:
        """Return the person-model context Honcho holds for this peer."""
        from app.services.processing_boundary import permit_external_processing
        await permit_external_processing()
        client = _get_client()
        resp = await client.get(self._url(f"/peers/{peer_id}/representation"))
        if resp.status_code == 404:
            return {}
        resp.raise_for_status()
        return resp.json()

    async def create_session(self, peer_id: str, session_id: str | None = None) -> dict:
        """Create a session under the peer."""
        from app.services.processing_boundary import permit_external_processing
        await permit_external_processing()
        await self.ensure_peer(peer_id)
        client = _get_client()
        sid = session_id or str(uuid.uuid4())
        resp = await client.post(
            self._url(f"/peers/{peer_id}/sessions"),
            json={"name": sid},
        )
        resp.raise_for_status()
        return resp.json()

    async def add_message(self, session_id: str, content: str, peer_name: str | None = None) -> dict:
        """Add a message to a session."""
        from app.services.processing_boundary import permit_external_processing
        await permit_external_processing()
        client = _get_client()
        resp = await client.post(
            self._url(f"/sessions/{session_id}/messages"),
            json={"content": content, "peer_name": peer_name},
        )
        resp.raise_for_status()
        return resp.json()

    async def chat(self, peer_id: str, message: str, session_id: str | None = None) -> str:
        """Send a message and get a response from the Honcho dialectic agent."""
        from app.services.processing_boundary import permit_external_processing
        await permit_external_processing()
        client = _get_client()
        resp = await client.post(
            self._url(f"/peers/{peer_id}/chat"),
            json={"message": message, "session_id": session_id},
        )
        resp.raise_for_status()
        data = resp.json()
        return data.get("response", "")

    async def health(self) -> bool:
        """Check if Honcho is reachable."""
        client = _get_client()
        try:
            resp = await client.get(f"{self.base_url}/health")
            return resp.status_code == 200
        except Exception:
            return False

    async def erase_peer(self, peer_id: str) -> None:
        """Only enabled after the installed service's full cascade is verified."""
        if not settings.honcho_erasure_verified:
            raise RuntimeError("Honcho erasure has not been verified")
        # Identifiers are generated by Pixie; URL path interpolation is bounded.
        import re
        if not re.fullmatch(r"sp-[a-fA-F0-9-]{36}", peer_id):
            raise ValueError("Invalid peer identity")
        result = await _get_client().delete(self._url(f"/peers/{peer_id}"))
        if result.status_code != 404:
            result.raise_for_status()
